create or replace function public.is_admin()
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from auth.users
    where id = auth.uid()
      and lower(email) = 'vaipracima10@gmail.com'
      and email_confirmed_at is not null
  );
$$;

create or replace function public.tocar_atualizado_em()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.atualizado_em := now();
  return new;
end $$;

-- ---------------------------------------------------------------------------
-- Peneiras: todo mundo vê as visíveis; só o administrador cria, edita e apaga.
-- ---------------------------------------------------------------------------
create table public.peneiras (
  id            bigint generated by default as identity primary key,
  origem_real   boolean not null default false,          -- true = "Peneira real", false = "Exemplo"
  clube         text not null check (length(clube) between 2 and 120),
  divisao       text not null,
  cidade        text not null,
  endereco      text,
  lat           double precision not null,
  lon           double precision not null,
  data          date not null,
  hora          time not null,
  horarios      text,                                     -- horários por categoria, um por linha
  preco         numeric(8,2) check (preco >= 0),          -- null = não informado, 0 = grátis
  vagas         int check (vagas >= 0),                   -- vagas abertas; null = não informado
  total         int check (total >= 0),
  cat_min       int not null check (cat_min between 9 and 20),
  cat_max       int not null check (cat_max between 9 and 20),
  ano_min       int,
  ano_max       int,
  generos       text[] not null check (cardinality(generos) > 0 and generos <@ array['M','F']),
  modalidades   text[] not null check (cardinality(modalidades) > 0 and modalidades <@ array['Futebol','Futsal']),
  levar         text,
  prazo         date,                                     -- inscrições até
  fonte_url     text check (fonte_url is null or fonte_url ~* '^https://'),
  fonte_texto   text,
  telefone      text,
  ativa         boolean not null default true,            -- false = oculta no app
  criado_em     timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  check (cat_min <= cat_max),
  check ((ano_min is null) = (ano_max is null) and (ano_min is null or ano_min <= ano_max))
);
create trigger peneiras_atualizado_em before update on public.peneiras
  for each row execute function public.tocar_atualizado_em();

alter table public.peneiras enable row level security;
create policy "peneiras: todos veem as visíveis" on public.peneiras
  for select to anon, authenticated using (ativa or public.is_admin());
create policy "peneiras: admin cria" on public.peneiras
  for insert to authenticated with check (public.is_admin());
create policy "peneiras: admin edita" on public.peneiras
  for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "peneiras: admin apaga" on public.peneiras
  for delete to authenticated using (public.is_admin());

-- ---------------------------------------------------------------------------
-- Perfis: as respostas do cadastro (ano, gênero, modalidade, cidade), nome,
-- WhatsApp e favoritas. Cada pessoa vê e muda só o seu; o admin vê todos.
-- E-mail e senha ficam no Supabase Auth (a senha nunca fica nesta tabela).
-- ---------------------------------------------------------------------------
create table public.perfis (
  id            uuid primary key references auth.users(id) on delete cascade,
  email         text,
  ano           int,
  genero        text check (genero in ('M','F')),
  modalidade    text check (modalidade in ('Futebol','Futsal')),
  cidade        text,
  usa_gps       boolean not null default false,
  nome          text,
  whatsapp      text,
  favoritas     bigint[] not null default '{}',
  criado_em     timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);
create trigger perfis_atualizado_em before update on public.perfis
  for each row execute function public.tocar_atualizado_em();

alter table public.perfis enable row level security;
create policy "perfis: dono ou admin leem" on public.perfis
  for select to authenticated using (id = auth.uid() or public.is_admin());
create policy "perfis: dono cria" on public.perfis
  for insert to authenticated with check (id = auth.uid());
create policy "perfis: dono edita" on public.perfis
  for update to authenticated using (id = auth.uid()) with check (id = auth.uid());
create policy "perfis: dono apaga" on public.perfis
  for delete to authenticated using (id = auth.uid());

-- ---------------------------------------------------------------------------
-- Interesses ("Tenho interesse", lista de espera e "Já me inscrevi").
-- Cada pessoa vê e cancela os seus; o admin vê e apaga todos.
-- ---------------------------------------------------------------------------
create table public.interesses (
  id           bigint generated by default as identity primary key,
  user_id      uuid not null default auth.uid() references auth.users(id) on delete cascade,
  peneira_id   bigint not null references public.peneiras(id) on delete cascade,
  nome         text,
  whatsapp     text,
  sub          int,
  genero       text check (genero in ('M','F')),
  lista_espera boolean not null default false,
  origem_real  boolean not null default false,
  criado_em    timestamptz not null default now(),
  unique (user_id, peneira_id)
);
create index interesses_peneira on public.interesses (peneira_id);

-- O banco decide se entra na lista de espera e de que tipo é o interesse
-- (o aparelho não consegue furar a fila mandando outro valor).
create or replace function public.interesse_antes()
returns trigger language plpgsql security definer set search_path = '' as $$
declare p public.peneiras;
begin
  select * into p from public.peneiras where id = new.peneira_id;
  if not found then raise exception 'Peneira não encontrada'; end if;
  new.user_id := auth.uid();
  new.origem_real := p.origem_real;
  new.lista_espera := not p.origem_real and p.vagas is not null and (
    select count(*) from public.interesses i
    where i.peneira_id = p.id and not i.lista_espera and not i.origem_real
  ) >= p.vagas;
  new.criado_em := now();
  return new;
end $$;
create trigger interesses_antes before insert on public.interesses
  for each row execute function public.interesse_antes();

alter table public.interesses enable row level security;
create policy "interesses: dono ou admin leem" on public.interesses
  for select to authenticated using (user_id = auth.uid() or public.is_admin());
create policy "interesses: dono cria em peneira visível" on public.interesses
  for insert to authenticated with check (
    user_id = auth.uid()
    and exists (select 1 from public.peneiras p where p.id = peneira_id and p.ativa)
  );
create policy "interesses: dono ou admin apagam" on public.interesses
  for delete to authenticated using (user_id = auth.uid() or public.is_admin());

-- Quantas vagas já foram ocupadas em cada peneira (só a contagem, sem dados pessoais).
create or replace function public.vagas_ocupadas()
returns table (peneira_id bigint, ocupadas int)
language sql stable security definer set search_path = ''
as $$
  select i.peneira_id, count(*)::int
  from public.interesses i
  where not i.lista_espera and not i.origem_real
  group by i.peneira_id;
$$;
revoke execute on function public.vagas_ocupadas() from public;
grant execute on function public.vagas_ocupadas() to anon, authenticated;

